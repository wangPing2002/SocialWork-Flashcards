def sha(s: str) -> str:
    return hashlib.sha256(s.encode('utf-8')).hexdigest()


def blocks_from(text: str):
    matches = list(re.finditer(r'(?m)^### (C\d{4})[ \t]*$', text))
    blocks = {}
    for i, m in enumerate(matches):
        blocks[m.group(1)] = (m.start(), matches[i + 1].start() if i + 1 < len(matches) else len(text))
    return blocks


def main() -> None:
    data = json.loads(zlib.decompress(base64.b85decode(B85.encode('ascii'))).decode('utf-8'))
    files = []
    for p in MASTER_DIR.glob('*.md'):
        try:
            b = p.read_bytes()
            s = b.decode('utf-8-sig')
        except (OSError, UnicodeError):
            continue
        if '### C0001' in s and '### C2497' in s:
            files.append(p)
    if len(files) != 1:
        sys.exit(f'ERROR: expected exactly one C0001-C2497 Markdown mother file; found {len(files)}. No changes made.')
    f = files[0]
    raw = f.read_bytes()
    bom = raw.startswith(b'\xef\xbb\xbf')
    eol = '\r\n' if b'\r\n' in raw else '\n'
    text = raw.decode('utf-8-sig').replace('\r\n', '\n')
    spans = blocks_from(text)
    if len(spans) != 2497:
        sys.exit(f'ERROR: expected 2497 card sections in the mother file, got {len(spans)}. No changes made.')
    cards = {c['id']: c for c in json.loads(CARDS.read_text('utf-8'))}
    replacements = []
    already = 0
    for cid, spec in data['blocks'].items():
        if cid not in spans or cid not in cards:
            sys.exit(f'ERROR: missing card {cid}. No changes made.')
        start, end = spans[cid]
        old_section = text[start:end]
        new_section = spec['new']
        oldhash = spec['old']
        if sha(old_section) == sha(new_section):
            already += 1
            continue
        if sha(old_section) != oldhash:
            sys.exit(f'ERROR: {cid} mother section differs from expected round-11 baseline. '
                     'Do not overwrite your manual edits. No changes made.')
        # The master must agree with the already patched app card for kind,
        # question and the reviewed answer; otherwise abort atomically.
        card = cards[cid]
        if f"- **题型**：{card['questionType']}" not in new_section or f"- **真题化问题**：{card['question']}" not in new_section:
            sys.exit(f'ERROR: {cid} master metadata conflicts with cards.json. No changes made.')
        answer = card['fullAnswer'].strip()
        if answer not in new_section:
            sys.exit(f'ERROR: {cid} master answer conflicts with cards.json. No changes made.')
        replacements.append((start, end, new_section))

    # Replace the old top-level reference guidance only if exactly known;
    # leave any independently revised guidance untouched rather than guessing.
    old_header, new_header = data['headers']['old'], data['headers']['new']
    if text.startswith(old_header):
        replacements.append((0, len(old_header), new_header))
    elif not text.startswith(new_header):
        print('NOTE: mother-file introductory notes were modified independently; preserving them.')

    for start, end, new_value in sorted(replacements, reverse=True):
        text = text[:start] + new_value + text[end:]
    out = text.replace('\n', eol).encode('utf-8')
    if bom:
        out = b'\xef\xbb\xbf' + out
    if raw != out:
        tmp = f.with_name(f.name + '.round12.tmp')
        tmp.write_bytes(out)
        os.replace(tmp, f)
    print(f'Round-12 mother sync successful: changed {len(replacements)} sections/header; '
          f'already synced {already}/{len(data["blocks"])} card sections. File: {f.name}')


if __name__ == '__main__':
    main()
